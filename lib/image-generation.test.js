const test = require('node:test');
const assert = require('node:assert/strict');
const { generateImage, imageBuffer, handleCreate } = require('./image-generation');
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');

test('image prompt goes directly to ZonerAI without Gemini credentials', async () => {
    const output = await generateImage('a cat & dog?', { http: { get: async (url, options) => {
        assert.equal(url, 'https://eliteprotech-apis.zone.id/ai/zonerai?prompt=a%20cat%20%26%20dog%3F');
        assert.equal(options.responseType, 'arraybuffer');
        assert.equal(options.headers, undefined);
        return { status: 200, data: png };
    } } });
    assert.deepEqual(output, png);
});

test('create sends validated generated bytes then success reaction', async () => {
    const sent = [];
    const socket = { sendMessage: async (chat, content) => { sent.push({ chat, content }); } };
    await handleCreate(socket, { chat: 'test@s.whatsapp.net', key: {} }, 'cat', '.create', { generate: async () => png });
    assert.deepEqual(sent[1].content.image, png);
    assert.equal(sent[2].content.react.text, '✅');
});

test('HTML and JSON errors never become images', async () => {
    assert.equal(imageBuffer(Buffer.from('<html>404</html>')), null);
    await assert.rejects(generateImage('cat', { http: { get: async () => ({ status: 200, data: Buffer.from('{"error":"no image"}') }) } }), { code: 'NO_IMAGE' });
});

test('image failures retain HTTP status without provider payloads', async () => {
    await assert.rejects(generateImage('cat', { http: { get: async () => ({ status: 503, data: 'secret-provider-payload' }) } }),
        error => error.status === 503 && !error.message.includes('secret-provider-payload'));
});

test('image errors are privately sent to the initiating user once', async () => {
    const sent = [];
    const socket = { sendMessage: async (chat, content) => { sent.push({ chat, content }); } };
    await handleCreate(socket, { chat: 'group@g.us', sender: 'person@s.whatsapp.net', key: {} }, 'cat', '.create', {
        generate: async () => { throw Object.assign(new Error('Image service returned HTTP 503.'), { status: 503 }); }
    });
    const errors = sent.filter(item => item.content.text);
    assert.equal(errors.length, 1);
    assert.equal(errors[0].chat, 'person@s.whatsapp.net');
    assert.match(errors[0].content.text, /HTTP 503/);
});